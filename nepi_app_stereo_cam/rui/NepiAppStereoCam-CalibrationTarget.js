// Decodes a base64 PDF into the byte array a Blob needs. atob gives one
// character per byte, so charCodeAt is the byte value.
function b64ToBytes(b64) {
  const binary = window.atob(b64)
  const bytes = new Uint8Array(binary.length)
  for (var i = 0; i < binary.length; i++) {
    bytes[i] = binary.charCodeAt(i)
  }
  return bytes
}


// Downloads a calibration target PDF to the VIEWING computer's browser Downloads
// folder -- not to the device. Same anchor-click mechanism the image viewer
// snapshot button uses (Nepi_IF_ImageViewer.saveImageFrame).
// paper: "letter" or "a4".
export function downloadCalibrationTarget(paper) {
  const target = TARGETS[paper]
  if (target === undefined) {
    return
  }
  const blob = new Blob([b64ToBytes(target.b64)], { type: "application/pdf" })
  const url = URL.createObjectURL(blob)
  const link = document.createElement("a")
  link.href = url
  link.download = target.filename
  document.body.appendChild(link)
  link.click()
  document.body.removeChild(link)
  URL.revokeObjectURL(url)
}
